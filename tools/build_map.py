#!/usr/bin/env python3
"""
PURPOSE:  Generate the layered repo map from the code with `ast` (modules are never imported): MAP.md (L0, small) and maps/<zone>.md (L1: cards, public signatures with line numbers, DEPENDS); enforces the card ratchet.
TAGS:     map, navigation, cards, signatures, docstring, ast, notebooks, ratchet, ci, tokens, الخريطة
PITFALLS: Output must stay deterministic (sorted, no timestamps) or `--check` flaps. Never hand-edit MAP.md or maps/. Notebook "cell N" is the 0-based index into the notebook's cells (all types), the same index tests/_cell uses. tools/card_allowlist.txt is a ratchet: it may only shrink, refresh it with `--update-allowlist` after cards are added.

Usage:
  python tools/build_map.py                    write MAP.md and maps/*.md
  python tools/build_map.py --check            exit 1 if maps are stale or the card ratchet is violated
  python tools/build_map.py --update-allowlist rewrite tools/card_allowlist.txt = exactly the .py files with no card
"""
from __future__ import annotations

import argparse
import ast
import copy
import json
import os
import posixpath
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_deps import (  # noqa: E402  (shared repo helpers)
    CODE_PACKAGES, ROOT, Repo, file_imports, notebook_cells, zone_of,
)

ALLOWLIST_PATH = "tools/card_allowlist.txt"
RATCHET_PREFIXES = ("cross_asset/", "tools/", "data/", "research/")
RATCHET_PREFIXES += ("workflow/", "discovery/")
DATA_EXTS = ("csv", "json", "log", "txt")
FIELDS = ("PURPOSE", "TAGS", "PITFALLS")
FIELD_RE = re.compile(r"^(PURPOSE|TAGS|PITFALLS)\s*:\s*(.*)$")
TITLE_MAX = 100
PURPOSE_MAX = 240
DEFAULT_MAX = 30
SIG_MAX = 200
MAP_TAG_REFS = 6
L0_MAX_LINES = 150  # PHILOSOPHY.md §4.2: MAP.md is imported by CLAUDE.md in every session
HEADER = "generated by tools/build_map.py — do not edit"


# --------------------------------------------------------------------------- text helpers
def squash(s: str, limit: int) -> str:
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= limit else s[: limit - 1].rstrip() + "…"


def first_heading(text: str) -> str:
    """First markdown heading, else first meaningful line."""
    lines = [ln.strip() for ln in text.splitlines()]
    for ln in lines:
        if ln.startswith("#"):
            h = ln.lstrip("#").strip()
            if h:
                return squash(h, TITLE_MAX)
    for ln in lines:
        if ln and not ln.startswith(("---", "<!--", "```")):
            return squash(ln, TITLE_MAX)
    return ""


def fmt_size(nbytes: int) -> str:
    return f"{nbytes} B" if nbytes < 1024 else f"{nbytes / 1024:.0f} KB"


def read_text(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8", errors="replace")


def parse_card(doc: str | None) -> dict[str, str]:
    """PURPOSE/TAGS/PITFALLS fields of a docstring (indented lines continue the previous field)."""
    out: dict[str, list[str]] = {}
    cur = None
    for raw in (doc or "").splitlines():
        m = FIELD_RE.match(raw)
        if m:
            cur = m.group(1)
            out[cur] = [m.group(2).strip()]
        elif cur and raw[:1] in (" ", "\t") and raw.strip():
            out[cur].append(raw.strip())
        else:
            cur = None
    return {k: " ".join(p for p in v if p) for k, v in out.items() if any(v)}


def split_tags(s: str) -> list[str]:
    s = s.strip().strip("[]()")
    parts = re.split(r"[,;،؛]", s) if re.search(r"[,;،؛]", s) else s.split()
    tags = []
    for p in parts:
        p = p.strip().strip("`'\"").strip().lower()
        if p and p not in tags:
            tags.append(p)
    return tags


# --------------------------------------------------------------------------- symbols
def _short_defaults(args: ast.arguments) -> ast.arguments:
    args = copy.deepcopy(args)
    for lst in (args.defaults, args.kw_defaults):
        for i, d in enumerate(lst):
            if d is not None and len(ast.unparse(d)) > DEFAULT_MAX:
                lst[i] = ast.Constant(value=Ellipsis)
    return args


def signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    try:
        s = f"({ast.unparse(_short_defaults(node.args))})"
        if node.returns is not None:
            s += f" -> {ast.unparse(node.returns)}"
    except Exception:  # pragma: no cover - defensive
        s = "(...)"
    return squash(s, SIG_MAX)


@dataclass
class Sym:
    kind: str  # def | class
    name: str
    sig: str
    line: int
    methods: list["Sym"] = field(default_factory=list)
    cell: int | None = None  # notebooks only
    extra: int = 0  # line within the cell (notebooks)


def _public(name: str) -> bool:
    return not name.startswith("_")


def top_symbols(body: list[ast.stmt]) -> list[Sym]:
    out: list[Sym] = []
    for n in body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and _public(n.name):
            kind = "async def" if isinstance(n, ast.AsyncFunctionDef) else "def"
            out.append(Sym(kind, n.name, signature(n), n.lineno))
        elif isinstance(n, ast.ClassDef) and _public(n.name):
            bases = ", ".join(ast.unparse(b) for b in n.bases)
            s = Sym("class", n.name, f"({squash(bases, 80)})" if bases else "", n.lineno)
            for m in n.body:
                if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and (_public(m.name) or m.name == "__init__"):
                    s.methods.append(Sym("def", m.name, signature(m), m.lineno))
            out.append(s)
    return out


def sym_lines(syms: list[Sym], count_only_methods: bool = False) -> list[str]:
    lines = []
    for s in syms:
        loc = f"cell {s.cell} L{s.extra}" if s.cell is not None else f"L{s.line}"
        lines.append(f"  - `{s.kind} {s.name}{s.sig}` {loc}")
        if s.methods:
            if count_only_methods:
                lines.append(f"    - ({len(s.methods)} methods)")
            else:
                for m in s.methods:
                    lines.append(f"    - `.{m.name}{m.sig}` L{m.line}")
    return lines


# --------------------------------------------------------------------------- module / notebook info
@dataclass
class Mod:
    path: str
    nlines: int
    doc: str | None
    card: dict[str, str]
    purpose: str
    purpose_src: str  # card | docstring | none
    syms: list[Sym]
    depends: list[str]
    parse_error: bool = False

    @property
    def has_card(self) -> bool:
        return bool(self.doc) or "PURPOSE" in self.card

    @property
    def tags(self) -> list[str]:
        return split_tags(self.card.get("TAGS", ""))


def analyse_module(repo: Repo, rel: str) -> Mod:
    text = read_text(rel)
    nlines = text.count("\n") + (1 if text and not text.endswith("\n") else 0)
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return Mod(rel, nlines, None, {}, "(no card)", "none", [], [], True)
    doc = ast.get_docstring(tree, clean=True)
    card = parse_card(doc)
    if "PURPOSE" in card:
        purpose, src = card["PURPOSE"], "card"
    elif doc and doc.strip():
        purpose, src = next(ln.strip() for ln in doc.splitlines() if ln.strip()), "docstring"
    else:
        purpose, src = "(no card)", "none"
    own = zone_of(rel)
    deps = set()
    for _, dotted, _shown in file_imports(tree, rel):
        z = repo.classify(dotted, rel)
        if z and z != own and z != "research":
            deps.add(z)
    return Mod(rel, nlines, doc, card, squash(purpose, PURPOSE_MAX), src, top_symbols(tree.body), sorted(deps))


@dataclass
class Notebook:
    path: str
    title: str
    n_cells: int
    n_code: int
    skipped: int
    headings: list[str]
    syms: list[Sym]
    depends: list[str]


def analyse_notebook(repo: Repo, rel: str) -> Notebook:
    parsed, md_cells, n_cells, n_code, skipped = notebook_cells(ROOT / rel)
    title = ""
    headings: list[str] = []
    for src in md_cells:
        if not title:
            title = first_heading(src)
        for ln in src.splitlines():
            m = re.match(r"^(#{1,2})\s+(.*\S)", ln)
            if m:
                headings.append(squash(m.group(2), TITLE_MAX))
    syms: list[Sym] = []
    deps: set[str] = set()
    for idx, _code, tree in parsed:
        for s in top_symbols(tree.body):
            s.cell, s.extra = idx, s.line
            syms.append(s)
        for _, dotted, _shown in file_imports(tree, rel):
            z = repo.classify(dotted, rel)
            if z and z not in ("root", "research"):
                deps.add(z)
    return Notebook(rel, title or "(no markdown)", n_cells, n_code, skipped, headings[:20], syms, sorted(deps))


# --------------------------------------------------------------------------- entries
@dataclass
class Entry:
    key: str  # e.g. cross_asset, research/edge_discovery, docs/research/audit
    mapfile: str  # maps/<mapfile>
    kind: str  # package | study | docs | tests
    files: list[str]
    recursive_label: str = ""

    def of(self, suffix: str) -> list[str]:
        return [f for f in self.files if f.endswith(suffix)]

    @property
    def py(self) -> list[str]:
        return self.of(".py")

    @property
    def md(self) -> list[str]:
        return self.of(".md")

    @property
    def data(self) -> list[str]:
        return [f for f in self.files if f.rsplit(".", 1)[-1] in DATA_EXTS and "." in posixpath.basename(f)]


def build_entries(repo: Repo) -> list[Entry]:
    files = [f for f in repo.files if f != ALLOWLIST_PATH]  # its size changes with every card added
    entries: list[Entry] = []
    for pkg in CODE_PACKAGES:
        fs = [f for f in files if f.startswith(pkg + "/")]
        if fs:
            entries.append(Entry(pkg, f"{pkg}.md", "package", fs))
    studies = sorted({f.split("/")[1] for f in files if f.startswith("research/") and f.count("/") >= 2})
    for s in studies:
        entries.append(Entry(f"research/{s}", f"research_{s}.md", "study", [f for f in files if f.startswith(f"research/{s}/")]))
    base = "docs/research"
    dfiles = [f for f in files if f.startswith(base + "/")]
    if dfiles:
        rel = lambda f: f[len(base) + 1:]  # noqa: E731
        entries.append(Entry(base, "docs_research.md", "docs", [f for f in dfiles if "/" not in rel(f)]))
        subdirs = sorted({rel(f).split("/")[0] for f in dfiles if "/" in rel(f)})
        for d in subdirs:
            if d == "scripts":
                entries.append(Entry(f"{base}/scripts", "docs_research.md", "docs",
                                     [f for f in dfiles if f.startswith(f"{base}/scripts/") and "/" not in f[len(base) + 9:]]))
                subs = sorted({f[len(base) + 9:].split("/")[0] for f in dfiles
                               if f.startswith(f"{base}/scripts/") and "/" in f[len(base) + 9:]})
                for sd in subs:
                    entries.append(Entry(f"{base}/scripts/{sd}", "docs_research.md", "docs",
                                         [f for f in dfiles if f.startswith(f"{base}/scripts/{sd}/")]))
            else:
                entries.append(Entry(f"{base}/{d}", "docs_research.md", "docs", [f for f in dfiles if f.startswith(f"{base}/{d}/")]))
    tests = [f for f in files if f.startswith("tests/")]
    if tests:
        entries.append(Entry("tests", "tests.md", "tests", tests))
    return entries


def entry_title(entry: Entry, mods: dict[str, Mod]) -> str:
    top = [f for f in entry.md if posixpath.dirname(f) == entry.key]
    pick = next((f for n in ("README.md", "REPORT.md") for f in top if posixpath.basename(f) == n), None)
    if pick is None and top and entry.kind in ("study", "docs") and entry.key != "docs/research":
        pick = sorted(top)[0]
    if pick:
        return first_heading(read_text(pick)) or "(empty heading)"
    init = mods.get(f"{entry.key}/__init__.py")
    if entry.kind in ("package", "tests") and init and init.purpose_src != "none":
        return init.purpose
    if entry.kind in ("package", "tests"):
        names = [posixpath.basename(f)[:-3] for f in entry.py if posixpath.dirname(f) == entry.key and not posixpath.basename(f).startswith("_")]
        return squash(", ".join(sorted(names)), TITLE_MAX)
    return "(no README)" if entry.kind in ("study", "docs") else ""


def total_size(files: list[str]) -> int:
    return sum((ROOT / f).stat().st_size for f in files)


def counts_phrase(entry: Entry) -> str:
    parts = [f"{len(entry.py)} scripts" if entry.kind in ("study", "docs") else f"{len(entry.py)} modules",
             f"{len(entry.data)} data files ({fmt_size(total_size(entry.data))})"]
    if entry.kind == "docs" and entry.md:
        parts.insert(1, f"{len(entry.md)} md")
    return ", ".join(parts)


# --------------------------------------------------------------------------- rendering
def short_ref(path: str) -> str:
    p = path[:-3] if path.endswith(".py") else path
    return p[len("research/"):] if p.startswith("research/") else p


def render_l0(repo: Repo, entries: list[Entry], mods: dict[str, Mod], nbs: list[Notebook]) -> str:
    L = [f"# MAP (L0) — {HEADER}", ""]
    L += ["Navigate: MAP.md (zone) → `maps/<zone>.md` (cards, public signatures, `L<line>`) → read the symbol by line range (Grep, then Read offset/limit).",
          "Cards: every module docstring may carry `PURPOSE:` / `TAGS:` / `PITFALLS:`; DEPENDS and signatures are derived. Notebook `cell N` = 0-based cell index.",
          "Refresh: `python tools/build_map.py`; verify: `python tools/build_map.py --check`; imports: `python tools/check_deps.py`.", ""]
    if nbs:
        L += ["## Root notebooks → maps/notebooks.md"]
        for nb in nbs:
            L.append(f"- `{nb.path}` — {nb.title} ({len(nb.syms)} public defs)")
        L.append("")
    sections = [("Code packages", "package"), ("Research studies (research/)", "study"), ("docs/research (legacy)", "docs"), ("Tests", "tests")]
    for head, kind in sections:
        es = [e for e in entries if e.kind == kind]
        if not es:
            continue
        L.append(f"## {head}")
        for e in es:
            title = entry_title(e, mods)
            nocard = sum(1 for f in e.py if not mods[f].has_card) if e.kind in ("package",) else 0
            extra = f", {nocard} without card" if nocard else ""
            L.append(f"- `{e.key}/` — {title + ' | ' if title else ''}{counts_phrase(e)}{extra} → maps/{e.mapfile}")
        L.append("")
    L += ["## Where do I edit X? → `maps/tags.md` (TAGS → modules index)", ""]
    return "\n".join(L).rstrip("\n") + "\n"


def render_tags(mods: dict[str, Mod]) -> str:
    """L1 TAGS → modules index (kept out of MAP.md so L0 stays small)."""
    index: dict[str, list[str]] = {}
    for p in sorted(mods):
        for t in mods[p].tags:
            index.setdefault(t, []).append(short_ref(p))
    L = [f"# TAGS → modules — {HEADER}", ""]
    for t in sorted(index):
        refs = index[t]
        shown = ", ".join(refs[:MAP_TAG_REFS]) + (f" … (+{len(refs) - MAP_TAG_REFS})" if len(refs) > MAP_TAG_REFS else "")
        L.append(f"- {t}: {shown}")
    return "\n".join(L).rstrip("\n") + "\n"


def render_module(m: Mod, tests: bool = False) -> list[str]:
    L = [f"### `{m.path}` ({m.nlines} lines)"]
    tag = "" if m.purpose_src == "card" else (" (from docstring)" if m.purpose_src == "docstring" else "")
    L.append(f"- PURPOSE: {m.purpose}{tag}")
    if "TAGS" in m.card:
        L.append(f"- TAGS: {', '.join(m.tags)}")
    if "PITFALLS" in m.card:
        L.append(f"- PITFALLS: {squash(m.card['PITFALLS'], 400)}")
    if m.depends:
        L.append(f"- DEPENDS: {', '.join(m.depends)}")
    if m.parse_error:
        L.append("- (syntax error: not parsed)")
    if m.syms:
        L.append("- API:")
        L += sym_lines(m.syms, count_only_methods=tests)
    return L


def render_entry(e: Entry, mods: dict[str, Mod], title: str) -> list[str]:
    L = [f"## `{e.key}/`", f"- {title + ' | ' if title else ''}{counts_phrase(e)}", ""]
    docs = [f for f in e.md]
    if docs:
        L.append("Documents:")
        for f in docs:
            L.append(f"- `{posixpath.relpath(f, e.key)}` — {first_heading(read_text(f)) or '(empty)'}")
        L.append("")
    for f in e.py:
        L += render_module(mods[f], tests=e.kind == "tests")
        L.append("")
    groups: dict[str, dict[str, list[int]]] = {}
    for f in e.files:
        ext = f.rsplit(".", 1)[-1] if "." in posixpath.basename(f) else "(none)"
        if ext in ("py", "md"):
            continue
        d = posixpath.relpath(posixpath.dirname(f), e.key)
        groups.setdefault(d, {}).setdefault(ext, []).append((ROOT / f).stat().st_size)
    if groups:
        L.append("Data / other files (counts only):")
        for d in sorted(groups):
            exts = groups[d]
            n = ", ".join(f"{x}×{len(exts[x])}" for x in sorted(exts))
            size = fmt_size(sum(sum(v) for v in exts.values()))
            L.append(f"- `{'.' if d == '.' else d + '/'}`: {n} — {size}")
        L.append("")
    return L


def render_l1(entries_in_file: list[Entry], mods: dict[str, Mod], titles: dict[str, str], name: str) -> str:
    L = [f"# {name} (L1) — {HEADER}", ""]
    for e in entries_in_file:
        L += render_entry(e, mods, titles[e.key])
    return "\n".join(L).rstrip("\n") + "\n"


def render_notebooks(nbs: list[Notebook]) -> str:
    L = [f"# Root notebooks (L1) — {HEADER}", "",
         "`cell N` = 0-based index into the notebook's cells (same index as `tests/_cell`); `L` = line within that cell. Magic (`%`) and shell (`!`) lines are dropped before parsing.", ""]
    for nb in nbs:
        L.append(f"## `{nb.path}`")
        L.append(f"- title: {nb.title}")
        skipped = f", {nb.skipped} code cells unparsable (skipped)" if nb.skipped else ""
        L.append(f"- cells: {nb.n_cells} ({nb.n_code} code{skipped})")
        if nb.depends:
            L.append(f"- DEPENDS: {', '.join(nb.depends)}")
        if nb.headings:
            L.append(f"- headings: {' · '.join(nb.headings)}")
        if nb.syms:
            L.append("- API:")
            L += sym_lines(nb.syms)
        L.append("")
    return "\n".join(L).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- generation + ratchet
def generate(repo: Repo) -> tuple[dict[str, str], dict[str, Mod]]:
    mods = {f: analyse_module(repo, f) for f in repo.py_files if "/" in f}
    entries = build_entries(repo)
    nbs = [analyse_notebook(repo, f) for f in repo.files if "/" not in f and f.endswith(".ipynb")]
    nbs.sort(key=lambda n: n.path)
    titles = {e.key: entry_title(e, mods) for e in entries}
    out = {"MAP.md": render_l0(repo, entries, mods, nbs)}
    if nbs:
        out["maps/notebooks.md"] = render_notebooks(nbs)
    out["maps/tags.md"] = render_tags(mods)
    by_file: dict[str, list[Entry]] = {}
    for e in entries:
        by_file.setdefault(e.mapfile, []).append(e)
    for mapfile, es in sorted(by_file.items()):
        out[f"maps/{mapfile}"] = render_l1(es, mods, titles, mapfile[:-3])
    return out, mods


def read_allowlist() -> list[str]:
    p = ROOT / ALLOWLIST_PATH
    if not p.is_file():
        return []
    return [ln.strip() for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip() and not ln.lstrip().startswith("#")]


def uncarded(mods: dict[str, Mod]) -> list[str]:
    return sorted(p for p, m in mods.items() if p.startswith(RATCHET_PREFIXES) and not m.has_card)


def ratchet_problems(mods: dict[str, Mod]) -> list[str]:
    allow = set(read_allowlist())
    bad = uncarded(mods)
    problems = [f"{p}: no card (add a docstring with PURPOSE/TAGS, or — legacy only — list it in {ALLOWLIST_PATH})"
                for p in bad if p not in allow]
    for p in sorted(allow):
        if p not in mods:
            problems.append(f"{ALLOWLIST_PATH}: stale entry (file no longer exists): {p}")
        elif mods[p].has_card:
            problems.append(f"{ALLOWLIST_PATH}: stale entry (file now has a card; remove it): {p}")
    return problems


def write_allowlist(mods: dict[str, Mod]) -> int:
    lines = ["# Legacy card debt: .py files in cross_asset/, tools/, data/, research/ that still have no card.",
             "# One path per line. This list may only shrink; generated by `python tools/build_map.py --update-allowlist`.", ""]
    bad = uncarded(mods)
    (ROOT / ALLOWLIST_PATH).write_text("\n".join(lines + bad) + "\n", encoding="utf-8", newline="\n")
    return len(bad)


def disk_state() -> dict[str, str]:
    cur = {}
    p = ROOT / "MAP.md"
    if p.is_file():
        cur["MAP.md"] = p.read_text(encoding="utf-8")
    for q in sorted((ROOT / "maps").glob("*.md")) if (ROOT / "maps").is_dir() else []:
        cur[f"maps/{q.name}"] = q.read_text(encoding="utf-8")
    return cur


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate MAP.md (L0) and maps/*.md (L1) from the code.")
    ap.add_argument("--check", action="store_true", help="fail if maps are stale or the card ratchet is violated")
    ap.add_argument("--update-allowlist", action="store_true", help=f"rewrite {ALLOWLIST_PATH} to exactly the uncarded files")
    args = ap.parse_args(argv)

    repo = Repo(ROOT)
    out, mods = generate(repo)

    if args.update_allowlist:
        n = write_allowlist(mods)
        print(f"build_map: wrote {ALLOWLIST_PATH} ({n} uncarded files)")
        return 0

    if args.check:
        disk = disk_state()
        stale = sorted(p for p in out if disk.get(p) != out[p]) + sorted(p for p in disk if p not in out)
        problems = ratchet_problems(mods)
        l0_lines = out["MAP.md"].count("\n")
        if l0_lines > L0_MAX_LINES:
            problems.append(f"MAP.md has {l0_lines} lines (> {L0_MAX_LINES}); move detail into maps/")
        for p in stale:
            print(f"stale: {p}" + ("" if p in out else " (not generated any more)"))
        for pr in problems:
            print(f"ratchet: {pr}")
        if stale or problems:
            print(f"build_map --check: FAILED ({len(stale)} stale files, {len(problems)} card problems); run `python tools/build_map.py`")
            return 1
        print(f"build_map --check: OK ({len(out)} files)")
        return 0

    (ROOT / "maps").mkdir(exist_ok=True)
    for p, text in out.items():
        (ROOT / p).write_text(text, encoding="utf-8", newline="\n")
    for p in disk_state():
        if p not in out:
            (ROOT / p).unlink()
    for pr in ratchet_problems(mods):
        print(f"warning: ratchet: {pr}")
    print(f"build_map: wrote {len(out)} files; MAP.md = {out['MAP.md'].count(chr(10))} lines")
